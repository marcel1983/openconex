def _parse(text):
    rows = [[float(v) for v in line.split()] for line in text.strip().splitlines()]
    assert len(rows) in (len(EX), len(EX) + 1) and all(len(r) == len(N) for r in rows)
    return dict(zip(EX, rows, strict=False)), (rows[len(EX)] if len(rows) > len(EX) else None)


def _bolts(n, s, gage):
    return [(x, s * i) for x in (0.0, gage) for i in range(n)]


def _close(value, table):
    return math.isclose(value, table, rel_tol=0.01, abs_tol=0.005)


@pytest.mark.parametrize("key", TABLES, ids=lambda k: f"{k[0]}-{k[2]}deg-s{k[3]:g}")
@pytest.mark.parametrize("sign", [1, -1])
def test_manual_table(key, sign):
    _, gage, angle, s = key
    rows, _ = _parse(TABLES[key])
    failures = []
    for ex, row in rows.items():
        for n, expected in zip(N, row, strict=True):
            c = icr_coefficient(_bolts(n, s, gage), (gage / 2 + ex, s * (n - 1) / 2),
                                angle=sign * angle).C
            if not _close(c, expected):
                failures.append(f"{key} ex={ex} n={n}: {c:.3f} vs {expected}")
    assert not failures, "\n".join(failures)


@pytest.mark.parametrize("key", [k for k in TABLES if k[2] == 0],
                         ids=lambda k: f"{k[0]}-s{k[3]:g}")
def test_pure_moment_c_prime(key):
    _, gage, _, s = key
    _, c_prime = _parse(TABLES[key])
    failures = []
    for n, expected in zip(N, c_prime, strict=True):
        bolts = _bolts(n, s, gage)
        cx, cy = gage / 2, s * (n - 1) / 2
        dist = [math.hypot(x - cx, y - cy) for x, y in bolts]
        mp = sum(_bolt_response(d, max(dist)) * d for d in dist)
        if not _close(mp, expected):
            failures.append(f"{key} n={n}: {mp:.3f} vs {expected}")
    assert not failures, "\n".join(failures)
