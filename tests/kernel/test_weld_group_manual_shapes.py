@pytest.mark.parametrize("case", CASES)
def test_manual_table(case):
    text, geometry, angle = CASES[case]
    failures = []
    for a, row in _parse(text).items():
        for k, expected in zip(K, row, strict=True):
            lines, load_point = geometry(k, a)
            c = icr_strength(lines, 1 / 16, 70.0, load_point, angle).Rn / L
            if not math.isclose(c, expected, rel_tol=0.01, abs_tol=0.005):
                failures.append(f"{case} a={a} k={k}: {c:.3f} vs {expected}")
    assert not failures, "\n".join(failures)


def test_channel_centroid_row():
    for k, expected in zip(K, X_ROW, strict=True):
        assert _x(k) == pytest.approx(expected, abs=0.0005)
