def _parse(text):
    rows = [[float(v) for v in line.split()] for line in text.strip().splitlines()]
    assert len(rows) == len(A) and all(len(r) == len(K) for r in rows)
    return dict(zip(A, rows, strict=True))


def _box(k, a):
    kl = k * L
    lines = [WeldLine(0, 0, 0, L), WeldLine(kl, 0, kl, L)]
    if k:
        lines += [WeldLine(0, 0, kl, 0), WeldLine(0, L, kl, L)]
    return lines, (kl / 2 + a * L, L / 2)


def _centroid(k):
    return k * k / (2 * (1 + k)), 1 / (2 * (1 + k))


def _angle(side):
    def geometry(k, a):
        x, y = _centroid(k)
        lines = [WeldLine(0, 0, 0, L)]
        if k:
            lines.append(WeldLine(0, 0, k * L, 0))
        return lines, ((x + side * a) * L, y * L)
    return geometry


CASES = {
    "8-6 angle 15": (TABLE_8_6_15, _box, 15),
    "8-6 angle 60": (TABLE_8_6_60, _box, 60),
    "8-10 angle 0": (TABLE_8_10_0, _angle(+1), 0),
    "8-10 angle 60": (TABLE_8_10_60, _angle(+1), 60),
    "8-11 angle 60": (TABLE_8_11_60, _angle(-1), 60),
}


@pytest.mark.parametrize("case", CASES)
def test_manual_table(case):
    text, geometry, angle = CASES[case]
    failures = []
    for a, row in _parse(text).items():
        for k, expected in zip(K, row, strict=True):
            lines, load_point = geometry(k, a)
            c = icr_strength(lines, 1 / 16, 70.0, load_point, angle).Rn / L
            if not math.isclose(c, expected, rel_tol=0.01, abs_tol=0.005):
                failures.append(f"{case} a={a} k={k}: {c:.3f} vs {expected}")
    assert not failures, "\n".join(failures)


def test_angle_centroid_rows():
    for k, x, y in zip(K, X_ROW, Y_ROW, strict=True):
        assert _centroid(k) == pytest.approx((x, y), abs=0.00051)  # table rounds half up
