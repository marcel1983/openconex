"""Convert the AISC Shapes Database (Excel) into the SQL file shipped with OpenConex.

Usage (needs ``pip install openpyxl``):

    python tools/build_shapes_db.py aisc-shapes-database-v16.0.xlsx \
        src/openconex/data/shapes/aisc_v16.sql

Only the U.S. customary block of the spreadsheet is read (the first occurrence
of each column name); values are copied as published, in U.S. units. The
loader in :mod:`openconex.core.shapes` converts them to internal units.
A dash ("–") or empty cell becomes NULL.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HEADER_KEY = "AISC_Manual_Label"
TEXT_COLUMNS = {"Type", "EDI_Std_Nomenclature", HEADER_KEY, "T_F"}
SQL_HEADER = """\
-- AISC Shapes Database {version}, U.S. customary values as published by AISC.
-- Source: American Institute of Steel Construction, https://www.aisc.org
-- Generated by tools/build_shapes_db.py from {source}. Do not edit by hand.
-- See NOTICE.md in this folder for attribution and terms.
"""


def _column_name(header: str) -> str:
    """SQL-safe column name: 'bf/2tf' -> 'bf_2tf', 'tan(α)' -> 'tan_alpha'."""
    name = header.strip().replace("α", "alpha")
    name = re.sub(r"[^0-9A-Za-z_]+", "_", name).strip("_")
    return name or "col"


def _sql_value(value: object) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, (int, float)):
        return repr(float(value)) if isinstance(value, float) else str(value)
    text = str(value).strip()
    if text in {"", "–", "—", "-"}:
        return "NULL"
    try:
        return repr(float(text))
    except ValueError:
        return "'" + text.replace("'", "''") + "'"


def convert(xlsx: Path, out: Path, version: str = "v16.0") -> int:
    from openpyxl import load_workbook

    wb = load_workbook(xlsx, read_only=True, data_only=True)
    sheet = next(
        (ws for ws in wb.worksheets if str(ws.title).lower().startswith("database")),
        wb.worksheets[0],
    )
    rows = sheet.iter_rows(values_only=True)
    header: list[str] = []
    for row in rows:
        cells = [str(c).strip() if c is not None else "" for c in row]
        if HEADER_KEY in cells:
            header = cells
            break
    if not header:
        raise SystemExit(f"header row with {HEADER_KEY!r} not found in {xlsx}")

    # First occurrence of each name = U.S. customary block.
    keep: list[tuple[int, str]] = []
    seen: set[str] = set()
    for idx, name in enumerate(header):
        col = _column_name(name) if name else ""
        if col and col not in seen:
            seen.add(col)
            keep.append((idx, col))

    lines = [SQL_HEADER.format(version=version, source=xlsx.name)]
    columns = ", ".join(f'"{c}" {"TEXT" if c in TEXT_COLUMNS else "REAL"}' for _, c in keep)
    lines.append(f"CREATE TABLE shapes ({columns});")
    names = ", ".join(f'"{c}"' for _, c in keep)
    label_idx = header.index(HEADER_KEY)
    count = 0
    for row in rows:
        if label_idx >= len(row) or not row[label_idx]:
            continue
        values = ", ".join(_sql_value(row[i] if i < len(row) else None) for i, _ in keep)
        lines.append(f"INSERT INTO shapes ({names}) VALUES ({values});")
        count += 1
    lines.append(f'CREATE UNIQUE INDEX shapes_label ON shapes ("{HEADER_KEY}");')
    lines.append('CREATE INDEX shapes_type ON shapes ("Type");')
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return count


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("xlsx", type=Path)
    parser.add_argument("out", type=Path)
    parser.add_argument("--version", default="v16.0")
    args = parser.parse_args(argv)
    count = convert(args.xlsx, args.out, args.version)
    print(f"{count} shapes written to {args.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
